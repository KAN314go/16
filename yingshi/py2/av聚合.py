    def searchContent(self, key, quick=False, pg="1"):
        try:
            pg = max(1, int(pg or 1))
        except Exception:
            pg = 1
        kw = str(key or "").strip()
        if not kw:
            return {"list": [], "page": pg, "pagecount": pg}

        conf = self.extend.get("search_src")
        if conf:
            keys = [k.strip() for k in str(conf).split(",") if k.strip()]
        else:
            keys = [s[0] for s in SOURCES if s[3]]
        if not keys:
            return {"list": [], "page": pg, "pagecount": pg}

        try:
            keep = max(1, int(self.extend.get("search_keep") or 12))
        except Exception:
            keep = 12
        try:
            workers = max(1, int(self.extend.get("search_workers") or 40))
        except Exception:
            workers = 40

        def work(k):
            try:
                d = self.http.api("/spiders/%s/search?wd=%s&pg=%d"
                                  % (_q(k), _q(kw), pg), timeout=8)
                return k, self._items(k, (d.get("list") or [])[:keep])
            except Exception:
                return k, []

        res = _pmap(work, keys, workers=workers, timeout=SEARCH_TIMEOUT)

        needle = re.sub(r"\s+", "", kw).lower()
        seen = set()
        hit_buckets, other_buckets = [], []
        for k in keys:
            hits, others = [], []
            for it in (res.get(k) or []):
                if it["vod_id"] in seen:
                    continue
                seen.add(it["vod_id"])
                rm = (it.get("vod_remarks") or "").strip()
                it["vod_remarks"] = (rm + " " + self._src_name(k)).strip()
                if needle in (it.get("vod_name") or "").lower():
                    hits.append(it)
                else:
                    others.append(it)
            if hits:
                hit_buckets.append(hits)
            if others:
                other_buckets.append(others)

        # 命中的排最前，同档位里按源轮播，避免一个源刷屏
        items = _interleave(hit_buckets) + _interleave(other_buckets)
        total = len(items)
        return {"list": items, "page": pg,
                "pagecount": pg + 1 if total else pg,
                "limit": keep * len(keys), "total": total}

    # ---------------- 播放 ----------------

    def playerContent(self, flag, id, vipFlags=None):
        raw = str(id or "")
        key = epflag = epid = ""
        parts = raw.split("|")
        if len(parts) >= 3:
            key, epflag = parts[0], parts[1]
            epid = _uq("|".join(parts[2:]))
        else:
            key = str(flag or "")
            epflag, epid = key, raw

        header = {"User-Agent": UA, "Referer": self.http.host + "/"}
        if not key:
            return {"parse": 0, "playUrl": "", "header": header}

        try:
            d = self.http.api("/spiders/%s/play?flag=%s&id=%s"
                              % (_q(key), _q(epflag), _q(epid)))
        except Exception:
            return {"parse": 0, "playUrl": "", "header": header}
        if not isinstance(d, dict):
            return {"parse": 0, "playUrl": "", "header": header}

        url = str(d.get("url") or "")
        if url.startswith("/"):
            url = self.http.host + url
        if not url:
            return {"parse": 0, "playUrl": "", "header": header}

        h = d.get("header") if isinstance(d.get("header"), dict) else {}
        h = dict(h)
        h.setdefault("User-Agent", UA)
        try:
            parse = int(d.get("parse") or 0)
        except Exception:
            parse = 0

        if self.extend.get("proxy"):
            try:
                if self._proxy is None:
                    self._proxy = _MediaProxy()
                port = self._proxy.start()
                if port:
                    _LOCAL_PORT[0] = port
                    tok = self._proxy.put(h)
                    return {"parse": 0,
                            "playUrl": "http://127.0.0.1:%d/jhtv?u=%s&t=%s"
                                       % (port, _q(url), tok),
                            "header": {"User-Agent": UA}}
            except Exception:
                pass

        return {"parse": parse, "playUrl": url, "header": h}

