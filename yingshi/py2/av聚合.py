def _q(s):
    return urllib.parse.quote(str(s if s is not None else ""), safe="")


def _uq(s):
    return urllib.parse.unquote(str(s or ""))


def _clean_name(s):
    """把详情页标题里的站点后缀清掉"""
    s = re.sub(r"<[^>]+>", "", str(s or "")).strip()
    s = re.sub(r"^在线播放", "", s)
    for mark in (" 在线播放", "在线观看", "在线播放 - "):
        i = s.find(mark)
        if i > 0:
            s = s[:i]
    return s.strip()


def _pmap(fn, items, workers=16, timeout=None):
    """极简并发执行：fn(item) -> (key, value)，返回 {key: value}"""
    items = list(items)
    n = len(items)
    out = {}
    if not n:
        return out
    lock = threading.Lock()
    cursor = [0]

    def run():
        while True:
            with lock:
                i = cursor[0]
                cursor[0] += 1
            if i >= n:
                return
            k, v = items[i], None
            try:
                k, v = fn(items[i])
            except Exception:
                pass
            with lock:
                out[k] = v

    threads = [threading.Thread(target=run)
               for _ in range(max(1, min(int(workers), n)))]
    for t in threads:
        t.daemon = True
        t.start()

    deadline = (time.time() + timeout) if timeout else None
    for t in threads:
        if deadline:
            left = deadline - time.time()
            if left <= 0:
                break
            t.join(left)
        else:
            t.join()
    return out


def _interleave(buckets):
    """多个列表按轮次交叉合并"""
    out = []
    i = 0
    while True:
        added = False
        for b in buckets:
            if i < len(b):
                out.append(b[i])
                added = True
        if not added:
            return out
        i += 1


class _Http(object):
    """统一网关客户端：多入口自动切换 + 重试"""

    def __init__(self, hosts=None):
        self.hosts = [h.rstrip("/") for h in (hosts or HOSTS)]
        if not self.hosts:
            self.hosts = ["https://av.telstra.com.cv"]
        self.host = self.hosts[0]
        self._lock = threading.Lock()

    def set_host(self, host):
        host = str(host or "").rstrip("/")
        if host:
            self.hosts = [host] + [h for h in self.hosts if h != host]
            self.host = host

    def _rotate(self):
        with self._lock:
            self.hosts = self.hosts[1:] + self.hosts[:1]
            self.host = self.hosts[0]

    def probe(self):
        for _ in range(len(self.hosts)):
            try:
                d = self._json(self.host + "/api/v1/spiders", retry=1)
                if isinstance(d, list) and d:
                    return self.host
            except Exception:
                pass
            self._rotate()
        return self.host

    def api(self, path, retry=2, timeout=TIMEOUT):
        url = self.host + "/api/v1" + path
        try:
            return self._json(url, retry=retry, timeout=timeout)
        except Exception:
            alt = self._rotate()
            return self._json(alt + "/api/v1" + path, retry=1, timeout=timeout)

    def _json(self, url, retry=2, timeout=TIMEOUT):
        last = None
        for i in range(max(1, retry)):
            try:
                req = urllib.request.Request(url)
                req.add_header("User-Agent", UA)
                req.add_header("Accept", "application/json, */*;q=0.8")
                req.add_header("Accept-Language", "zh-CN,zh;q=0.9")
                req.add_header("Referer", self.host + "/")
                with urllib.request.urlopen(req, timeout=timeout) as r:
                    raw = r.read()
                return json.loads(raw.decode("utf-8", "ignore"))
            except Exception as e:
                last = e
                if i + 1 < retry:
                    time.sleep(0.3)
        raise last if last else RuntimeError("request failed")


def _abs_url(uri, base):
    if not uri:
        return ""
    uri = uri.strip()
    if uri.startswith("//"):
        return "https:" + uri
    if re.match(r"^https?://", uri, re.I):
        return uri
    try:
        return urllib.parse.urljoin(base, uri)
    except Exception:
        return uri


