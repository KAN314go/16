class _MediaProxy(object):

    def __init__(self):
        self.port = 0
        self._started = False
        self._ctx = {}
        self._seq = 0
        self._lock = threading.Lock()

    def put(self, headers):
        with self._lock:
            self._seq += 1
            tok = "%d%05d" % (self._seq, int(time.time()) % 100000)
            self._ctx[tok] = dict(headers or {})
            if len(self._ctx) > 32:
                for k in list(self._ctx)[:-16]:
                    self._ctx.pop(k, None)
        return tok

    def start(self):
        if self._started:
            return self.port
        from http.server import BaseHTTPRequestHandler, HTTPServer

        proxy = self

        class H(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def log_message(self, *a):
                pass

            def _fail(self, code, msg):
                body = (msg or "").encode("utf-8")
                try:
                    self.send_response(code)
                    self.send_header("Content-Type", "text/plain; charset=utf-8")
                    self.send_header("Content-Length", str(len(body)))
                    self.end_headers()
                    self.wfile.write(body)
                except Exception:
                    pass

            def _serve(self):
                qs = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
                target = (qs.get("u") or [""])[0]
                tok = (qs.get("t") or [""])[0]
                if not target:
                    return self._fail(404, "no target")
                headers = dict(proxy._ctx.get(tok) or {})
                rng = self.headers.get("Range")
                try:
                    req = urllib.request.Request(target)
                    if not headers.get("User-Agent"):
                        headers["User-Agent"] = UA
                    for k, v in headers.items():
                        try:
                            req.add_header(k, v)
                        except Exception:
                            pass
                    if rng:
                        req.add_header("Range", rng)
                    resp = urllib.request.urlopen(req, timeout=60)
                except Exception as e:
                    return self._fail(502, "proxy error: " + str(e)[:180])

                ctype = resp.headers.get("Content-Type", "") or ""
                is_pl = (target.split("?")[0].lower().endswith(".m3u8")
                         or "mpegurl" in ctype.lower())

                if is_pl:
                    try:
                        text = resp.read().decode("utf-8", "ignore")
                    finally:
                        try:
                            resp.close()
                        except Exception:
                            pass
                    data = _rewrite_playlist(text, target, tok).encode("utf-8")
                    self.send_response(200)
                    self.send_header("Content-Type", "application/vnd.apple.mpegurl")
                    self.send_header("Content-Length", str(len(data)))
                    self.send_header("Access-Control-Allow-Origin", "*")
                    self.end_headers()
                    try:
                        self.wfile.write(data)
                    except Exception:
                        pass
                    return

                code = 206 if (rng and getattr(resp, "status", 200) == 206) else 200
                clen = resp.headers.get("Content-Length")
                self.send_response(code)
                self.send_header("Content-Type", ctype or "application/octet-stream")
                self.send_header("Accept-Ranges", "bytes")
                self.send_header("Access-Control-Allow-Origin", "*")
                if resp.headers.get("Content-Range"):
                    self.send_header("Content-Range", resp.headers["Content-Range"])
                    if clen:
                        self.send_header("Content-Length", clen)
                elif clen:
                    self.send_header("Content-Length", clen)
                else:
                    self.close_connection = True
                self.end_headers()
                try:
                    while True:
                        chunk = resp.read(262144)
                        if not chunk:
                            break
                        self.wfile.write(chunk)
                except Exception:
                    pass
                finally:
                    try:
                        resp.close()
                    except Exception:
                        pass

            def do_GET(self):
                if self.path.startswith("/jhtv"):
                    return self._serve()
                return self._fail(404, "not found")

            def do_HEAD(self):
                self.send_response(200)
                self.send_header("Content-Length", "0")
                self.end_headers()

        s = socket.socket()
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
        s.close()
        srv = HTTPServer(("127.0.0.1", port), H)
        threading.Thread(target=srv.serve_forever,
                         kwargs={"poll_interval": 0.5}, daemon=True).start()
        self.port = port
        self._started = True
        return port


def _rewrite_playlist(text, base, tok):
    """m3u8 里的分片 / 密钥地址相对路径补全，并统一指回本机代理"""
    out = []
    for ln in (text or "").splitlines():
        if ln.startswith("#EXT-X-KEY") or ln.startswith("#EXT-X-MAP"):
            def _rw(m):
                u = _abs_url(m.group(2), base)
                return '%s"http://127.0.0.1:%d/jhtv?u=%s&t=%s"' % (
                    m.group(1), _LOCAL_PORT[0], _q(u), tok)
            out.append(re.sub(r'(URI=)"([^"]+)"', _rw, ln))
            continue
        if ln and not ln.startswith("#"):
            u = _abs_url(ln.strip(), base)
            out.append("http://127.0.0.1:%d/jhtv?u=%s&t=%s"
                       % (_LOCAL_PORT[0], _q(u), tok))
            continue
        out.append(ln)
    return "\n".join(out) + "\n"


